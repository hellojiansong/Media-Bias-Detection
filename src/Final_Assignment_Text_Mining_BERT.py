stop_words = set(stopwords.words('english'))

def f(texts):
    texts = [str(t) for t in texts]
    enc = tokenizer(
        texts,
        truncation=True,
        padding="max_length",
        max_length=128,
        return_tensors="pt"
    )
    input_ids = enc["input_ids"].to(model.device)
    attention_mask = enc["attention_mask"].to(model.device)
    with torch.no_grad():
        logits = model(input_ids=input_ids, attention_mask=attention_mask).logits
        probs = torch.softmax(logits, dim=1).cpu().numpy()
    return probs

background_sentences = val_df["sentence"].dropna().astype(str).tolist()[:20]

explainer = shap.Explainer(
    f,
    masker=shap.maskers.Text(tokenizer, mask_token="[MASK]"),
    output_names=["Unbiased", "Biased"]
)

overall = {}

for sentence in false_positives["sentence"].dropna().astype(str):
    shap_values = explainer([sentence])

    pred_class = np.argmax(shap_values.base_values + shap_values.values[0].sum(axis=0))

    tokens = tokenizer.tokenize(sentence)
    contributions = shap_values.values[0][:, pred_class]

    word = ""
    word_weight = 0
    for t, w in zip(tokens, contributions):
        if t.startswith("##"):
            word += t[2:]
            word_weight += w
        else:
            if word:
                if word.lower() not in stop_words and word not in string.punctuation:
                    overall[word] = overall.get(word, 0) + word_weight
            word = t
            word_weight = w
    if word:
        if word.lower() not in stop_words and word not in string.punctuation:
            overall[word] = overall.get(word, 0) + word_weight

df_overall = pd.DataFrame(overall.items(), columns=["token", "weight"])
df_overall["abs_weight"] = df_overall["weight"].abs()
top10_overall = df_overall.sort_values(by="abs_weight", ascending=False).head(10).drop(columns="abs_weight").reset_index(drop=True)

